// Builds the platform files in dist/ from the tokens in tokens/. Run `npm run build`.
//
// Style Dictionary reads and checks the tokens (DTCG format) once per theme; the files are
// written here, because each one holds both themes.
import { copyFile, mkdir, readdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import StyleDictionary from 'style-dictionary';

const here = dirname(new URL(import.meta.url).pathname);
const dist = join(here, 'dist');
const themes = ['light', 'dark'];

/** Token files every theme reads; each theme adds its own color-<theme>.json. */
const shared = (await readdir(join(here, 'tokens'))).filter((f) => f.endsWith('.json') && !f.startsWith('color-')).sort();

const header = 'Generated by design/build.mjs from design/tokens. Do not edit: change the tokens and run `npm run build`.';

/** Kotlin package of the generated tokens. */
const kotlinPackage = 'org.tidefell.design';

/** Tokens the Android app needs as resources: the window behind Compose, and the launcher icon. */
const androidResources = ['color.bg', 'color.accent.base', 'brand.mark'];

async function load(theme) {
  // Every theme reads the shared files and its own colours.
  const sd = new StyleDictionary({
    usesDtcg: true,
    log: { warnings: 'error', verbosity: 'verbose' },
    source: [...shared, `color-${theme}.json`].map((f) => join(here, 'tokens', f)),
    platforms: { raw: {} },
  });
  const { allTokens } = await sd.getPlatformTokens('raw');
  return allTokens.map((t) => ({
    path: t.path,
    key: t.path.join('.'),
    type: t.$type,
    value: t.$value,
    description: t.$description,
  }));
}

/**
 * A token's name as the platforms spell it: without a trailing `base`, so `color.accent.base` is
 * plain `accent`, and with `on` first, so `color.accent.on-soft` is `on-accent-soft`.
 */
const parts = (path) => {
  const last = path.at(-1);
  if (last === 'base') return path.slice(0, -1);
  if (last === 'on' || last.startsWith('on-')) return [...path.slice(0, -2), 'on', path.at(-2), ...last.split('-').slice(1)];
  return path;
};
const camel = (words) =>
  words
    .flatMap((w) => w.split('-'))
    .map((w, i) => (i === 0 ? w : w[0].toUpperCase() + w.slice(1)))
    .join('');
const pascal = (words) => {
  const c = camel(words);
  return c[0].toUpperCase() + c.slice(1);
};
const hex = (value) => {
  if (!/^#[0-9a-f]{6}$/.test(value)) throw new Error(`Colours are #rrggbb in lower case, not ${value}`);
  return value.slice(1).toUpperCase();
};
const size = (value) => {
  if (value.unit !== 'px') throw new Error(`Dimensions are in px, not ${value.unit}`);
  return value.value;
};
const group = (tokens, name) => tokens.filter((t) => t.path[0] === name);
const kdoc = (t, indent) => (t.description ? [`${indent}/** ${t.description} */`] : []);

/** Every text style is in Inter, the sans family, which ui/Theme.kt gives to Compose. */
function sansOnly(tokens) {
  const sans = JSON.stringify(tokens.find((t) => t.key === 'font.family.sans').value);
  for (const t of group(tokens, 'text')) {
    if (JSON.stringify(t.value.fontFamily) !== sans) throw new Error(`${t.key} is not in font.family.sans`);
  }
}

function kotlin(byTheme) {
  const [light] = themes.map((th) => byTheme[th]);
  const colors = group(light, 'color');
  const field = (t) => camel(parts(t.path).slice(1));
  const lines = [
    `// ${header}`,
    `package ${kotlinPackage}`,
    '',
    'import androidx.compose.runtime.Immutable',
    'import androidx.compose.ui.graphics.Color',
    'import androidx.compose.ui.text.font.FontWeight',
    'import androidx.compose.ui.unit.TextUnit',
    'import androidx.compose.ui.unit.dp',
    'import androidx.compose.ui.unit.sp',
    '',
    '/** Tidefell\'s colours in one theme, light or dark. */',
    '@Immutable',
    'data class TidefellColors(',
  ];
  for (const t of colors) {
    if (t.description) lines.push(`    /** ${t.description} */`);
    lines.push(`    val ${field(t)}: Color,`);
  }
  lines.push(')', '');
  for (const theme of themes) {
    const name = pascal([theme]);
    lines.push(`/** The ${theme} theme's colours. */`, `val Tidefell${name}Colors = TidefellColors(`);
    for (const t of group(byTheme[theme], 'color')) lines.push(`    ${field(t)} = Color(0xFF${hex(t.value)}),`);
    lines.push(')', '');
  }
  lines.push('/** Colours that are the same in light and dark. */', 'object TidefellBrand {');
  for (const t of group(light, 'brand')) {
    if (t.description) lines.push(`    /** ${t.description} */`);
    lines.push(`    val ${pascal(parts(t.path).slice(1))} = Color(0xFF${hex(t.value)})`);
  }
  lines.push('}');
  for (const [name, doc] of [
    ['radius', 'Corner radii.'],
    ['space', 'Space between and around things.'],
    ['size', 'Sizes of things.'],
  ]) {
    lines.push('', `/** ${doc} */`, `object Tidefell${pascal([name])} {`);
    for (const t of group(light, name)) lines.push(...kdoc(t, '    '), `    val ${pascal(parts(t.path).slice(1))} = ${size(t.value)}.dp`);
    lines.push('}');
  }
  lines.push(
    '',
    '/** A text style in Inter; ui/Theme.kt makes Compose text styles of them. */',
    '@Immutable',
    'data class TidefellTextStyle(val weight: FontWeight, val size: TextUnit, val lineHeight: TextUnit, val letterSpacing: TextUnit)',
    '',
    '/** Text styles. */',
    'object TidefellText {',
  );
  for (const t of group(light, 'text')) {
    const v = t.value;
    lines.push(
      ...kdoc(t, '    '),
      `    val ${pascal(parts(t.path).slice(1))} = TidefellTextStyle(` +
        `FontWeight(${v.fontWeight}), ${size(v.fontSize)}.sp, ${size(v.lineHeight)}.sp, ${size(v.letterSpacing)}.sp)`,
    );
  }
  lines.push('}', '');
  return lines.join('\n');
}

function androidXml(tokens, keys) {
  const lines = ['<?xml version="1.0" encoding="utf-8"?>', `<!-- ${header} -->`, '<resources>'];
  for (const t of tokens.filter((x) => keys.includes(x.key))) {
    lines.push(`    <color name="tidefell_${parts(t.path).join('_').replaceAll('-', '_')}">#${hex(t.value)}</color>`);
  }
  lines.push('</resources>', '');
  return lines.join('\n');
}

function css(byTheme) {
  const variable = (t) => `--tf-${parts(t.path).join('-')}`;
  const family = (names) => names.map((n) => (/^[a-z-]+$/.test(n) ? n : `"${n}"`)).join(', ');
  const value = (t) => {
    if (t.type === 'dimension') return `${size(t.value)}px`;
    if (t.type === 'fontFamily') return family(t.value);
    // A typography token is the font shorthand; its letter spacing is a variable of its own.
    if (t.type === 'typography') {
      const v = t.value;
      return `${v.fontWeight} ${size(v.fontSize)}px/${size(v.lineHeight)}px ${family(v.fontFamily)}`;
    }
    return t.value;
  };
  const line = (t, indent) => {
    const out = [`${indent}${variable(t)}: ${value(t)};`];
    if (t.type === 'typography' && size(t.value.letterSpacing) !== 0) {
      out.push(`${indent}${variable(t)}-letter-spacing: ${size(t.value.letterSpacing)}px;`);
    }
    return out;
  };
  const block = (tokens, indent) => tokens.flatMap((t) => line(t, indent));
  const light = byTheme.light;
  // Only what differs between the themes goes in the dark block.
  const darkOnly = byTheme.dark.filter((t) => JSON.stringify(light.find((l) => l.key === t.key)?.value) !== JSON.stringify(t.value));
  return [
    `/* ${header} */`,
    ':root {',
    ...block(light, '  '),
    '}',
    '',
    '@media (prefers-color-scheme: dark) {',
    '  :root {',
    ...block(darkOnly, '    '),
    '  }',
    '}',
    '',
  ].join('\n');
}

async function write(path, text) {
  await mkdir(dirname(join(dist, path)), { recursive: true });
  await writeFile(join(dist, path), text);
  console.log(`dist/${path}`);
}

const byTheme = Object.fromEntries(await Promise.all(themes.map(async (th) => [th, await load(th)])));
const names = (th) => byTheme[th].map((t) => t.key).join(',');
if (names('light') !== names('dark')) throw new Error('color-light.json and color-dark.json must name the same tokens');
for (const key of androidResources) {
  if (!byTheme.light.some((t) => t.key === key)) throw new Error(`No token ${key} for an Android resource`);
}

sansOnly(byTheme.light);

await write(`android/kotlin/${kotlinPackage.replaceAll('.', '/')}/Tokens.kt`, kotlin(byTheme));
await write('android/res/values/tidefell_tokens.xml', androidXml(byTheme.light, androidResources));
// Only the themed colours; the brand's are the same at night.
await write(
  'android/res/values-night/tidefell_tokens.xml',
  androidXml(byTheme.dark, androidResources.filter((k) => k.startsWith('color.'))),
);
await write('css/tokens.css', css(byTheme));
await mkdir(join(dist, 'android/res/font'), { recursive: true });
await copyFile(join(here, 'fonts/InterVariable.ttf'), join(dist, 'android/res/font/inter.ttf'));
console.log('dist/android/res/font/inter.ttf');
